
#TUPLE TANIMLAMA
demet = (1,2,3,4)
demet = (1,)
print(type(demet)) # <class 'tuple'>

# TUPLE ELEMAN EKLEME
demet = (1,)
demet += ("1",)
print(demet) #(1, '1')

# TUPLE ELEMANLARINA ERİŞMEK
demet = (1,2,3,4,5) 
print(demet[1:2]) #(2,)

# INDEX FONKSİYONU
demet = ["1","2","3"]
demet.index("2") # 1

# COUNT FONKSİYONU
demet = ["1","2","3"]
demet.count("2") # 1



























